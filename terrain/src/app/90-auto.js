/* 90-auto.js — headless auto-capture flythrough and route benchmark driver.
   DECLARES: AUTO, streamsBusy, settleStreams, sampleFrames, runBenchmarkRoute, runAuto.
   CONSUMES: terrain (40), overlay/labelGroup/realLabels (84/70), state/drive/placeCar (80/82),
     camera (20), sampleGround (40), day/updateSun (30), Minimap (88), saveShot/saveMinimapShot (86/88),
     EYE (80), renderer (20), lerp (00),
     updateMode (84). */
/* ============================================================
   AUTO-CAPTURE — headless review shots, no human at the wheel.
   ?auto=views.json            fly a list of saved views, shoot each one
   ?auto=1&name=x&pos=x,y,z&yaw=r&pitch=r&time=t   single view inline
   Each view: {name, pos:[x,y,z], yaw, pitch, time?, weather?, phase?, ground?}
   (ground: y = terrain + 3 m). `nosettle` intentionally records the loading transition.
   Streams settle before each shot; sets document.title=AUTO_DONE when finished.
   ============================================================ */
const AUTO=new URLSearchParams(location.search).get('auto');
function streamsBusy(){
  const t=terrain && (terrain.fetchQueue.length || terrain.uploadQueue.length || terrain.inFlight);
  const incomplete=terrain && terrain.coverageSnapshot && !terrain.coverageSnapshot().complete;
  const surfaces=(waterBuilder&&waterBuilder._refining)||(roadRibbon&&roadRibbon._pass)||
    (trailBuilder&&trailBuilder._pass);
  return !!t || !!incomplete || !!surfaces || !!window.carModelLoading; // wait for final authoritative surfaces too
}
function settleStreams(){
  return new Promise(res=>{
    const started=performance.now();
    let calm=0, frames=0;
    const iv=setInterval(()=>{
      frames++;
      calm = streamsBusy() ? 0 : calm+1;
      if((calm>25 && frames>45) || frames>900){
        clearInterval(iv);
        const visibleTerrainCoverage=terrain&&terrain.coverageSnapshot?
          terrain.coverageSnapshot():null;
        res({
          settleMs:+(performance.now()-started).toFixed(1),
          settleTimedOut:frames>900,
          coverageRequired:true,
          visibleTerrainCoverage,
        });
      }  // ≤ ~30 s per view
    },33);
  });
}
function sampleFrames(count=90){
  return new Promise(res=>{
    const samples=[];
    let last=performance.now();
    function tick(now){
      const elapsed=now-last; last=now;
      if(elapsed>0 && elapsed<1000) samples.push(elapsed);
      if(samples.length<count) requestAnimationFrame(tick);
      else{
        samples.sort((a,b)=>a-b);
        const mean=samples.reduce((a,b)=>a+b,0)/samples.length;
        const p99=samples[Math.min(samples.length-1,Math.floor(samples.length*.99))];
        res({
          sampledFrames:samples.length,
          meanFrameMs:+mean.toFixed(2),
          p99FrameMs:+p99.toFixed(2),
          averageFps:+(1000/mean).toFixed(1),
          onePercentLowFps:+(1000/p99).toFixed(1)
        });
      }
    }
    requestAnimationFrame(tick);
  });
}
async function runBenchmarkRoute(v){
  const points=v.waypoints||[];
  if(points.length<2) throw new Error('route requires at least two waypoints');
  // Certification frames must remain unobscured and comparable across routes.
  realLabels.on=false;
  labelGroup.visible=false;
  const duration=Math.max(1,+(v.durationSeconds||8))*1000;
  if(v.time!==undefined){ day.t=v.time; updateSun(true); requestSkyEnvironmentRebake(); }
  if(v.mode==='drive'){
    drive.on=true; drive.used=true; drive.camMode=v.cameraMode===undefined?0:v.cameraMode;
    drive.camDist=drive.camMode===1?7.5:14;
    placeCar(points[0].pos[0],points[0].pos[2],points[0].yaw||0,100);
    state.yaw=points[0].yaw||0;
    drive.fpYaw=0;
    drive.snapCam=true; updateMode();
  }else{
    if(drive.on){ drive.on=false; updateMode(); }
    const first=points[0];
    camera.position.set(first.pos[0],sampleGround(first.pos[0],first.pos[2])+(v.eyeHeight||EYE),first.pos[2]);
    state.yaw=first.yaw||0;state.pitch=first.pitch||0;
  }
  // Establish the route origin before sampling. This excludes the artificial fast-travel into the
  // first waypoint while retaining all streaming generated by the actual route traversal.
  const prewarmStarted=performance.now();
  await settleStreams();
  const prewarmMs=performance.now()-prewarmStarted;
  const started=performance.now(), seenTiles=new Set(), frameTimes=[];
  let last=started, maxFrame=0, peakTextures=0, peakCalls=0, peakTris=0, busyFrames=0, tilePops=0;
  const frameSpikes=[];
  let tileBaselineReady=false;
  await new Promise((resolve,reject)=>{
    function frame(now){
      try{
      const elapsed=now-started, u=Math.max(0,Math.min(1,elapsed/duration));
      const scaled=u*(points.length-1), index=Math.min(points.length-2,Math.floor(scaled));
      const local=scaled-index, a=points[index], b=points[index+1];
      const x=lerp(a.pos[0],b.pos[0],local), z=lerp(a.pos[2],b.pos[2],local);
      const yaw=lerp(a.yaw||0,b.yaw||0,local), pitch=lerp(a.pitch||0,b.pitch||0,local);
      if(v.mode==='drive'){
        drive.pos.x=x; drive.pos.z=z; drive.pos.y=sampleGround(x,z);
        drive.yaw=yaw; drive.speed=0; drive.snapCam=true;
        state.yaw=yaw; drive.fpYaw=0;
        // The certification runner moves between authored poses rather than integrating vehicle
        // velocity. Do not carry spring energy from the previous teleported pose into the next
        // one: it can leave the display SUV buried or tilted even when rendered/query surfaces
        // agree. Re-seed contacts and let the normal physics step solve the current pose.
        if(typeof vehiclePhysicsState!=='undefined'&&vehiclePhysicsState){
          vehiclePhysicsState.yaw=yaw; vehiclePhysicsState.speed=0;
          const suspension=vehiclePhysicsState.suspension;
          suspension.y=null; suspension.heaveVelocity=0;
          suspension.pitch=0; suspension.roll=0;
          suspension.pitchVelocity=0; suspension.rollVelocity=0;
          for(const wheel of suspension.wheels){ wheel.y=null; wheel.velocity=0; }
        }
      }else{
        camera.position.set(x,sampleGround(x,z)+(v.eyeHeight||EYE),z);
        state.yaw=yaw; state.pitch=pitch; state.fly=false; state.vel.set(0,0,0);
      }
      const dt=now-last; last=now;
      if(dt>0) maxFrame=Math.max(maxFrame,dt);
      if(dt>0&&dt<1000) frameTimes.push(dt);
      if(dt>33&&frameSpikes.length<24) frameSpikes.push({
        atMs:+elapsed.toFixed(1),dt:+dt.toFixed(1),
        terrain:terrain?{
          fetch:terrain.fetchQueue.length,upload:terrain.uploadQueue.length,
          inFlight:terrain.inFlight,meshes:terrain.meshes.size,
        }:null,
        waterRefining:!!(waterBuilder&&waterBuilder._refining),
        roadPass:!!(roadRibbon&&roadRibbon._pass),
        trailPass:!!(trailBuilder&&trailBuilder._pass),
      });
      if(streamsBusy()) busyFrames++;
      peakTextures=Math.max(peakTextures,renderer.info.memory.textures);
      const sceneInfo=postFX && postFX.lastSceneInfo;
      peakCalls=Math.max(peakCalls,sceneInfo?sceneInfo.calls:renderer.info.render.calls);
      peakTris=Math.max(peakTris,sceneInfo?sceneInfo.triangles:renderer.info.render.triangles);
      if(terrain){
        for(const [key,entry] of terrain.meshes)
          if(entry.mesh && entry.mesh.visible && !seenTiles.has(key)){
            seenTiles.add(key);
            if(tileBaselineReady) tilePops++;
          }
        tileBaselineReady=true;               // initial visible working set is not a traversal pop
      }
      if(u<1) requestAnimationFrame(frame); else resolve();
      }catch(err){ reject(err); }
    }
    requestAnimationFrame(frame);
  });
  frameTimes.sort((a,b)=>a-b);
  const mean=frameTimes.reduce((a,b)=>a+b,0)/Math.max(1,frameTimes.length);
  const p99=frameTimes[Math.min(frameTimes.length-1,Math.floor(frameTimes.length*.99))]||0;
  return {
    routeMode:v.mode||'hike', routePrewarmMs:+prewarmMs.toFixed(1),
    routeDurationMs:+(performance.now()-started).toFixed(1),
    routeFrames:frameTimes.length, meanFrameMs:+mean.toFixed(2), p99FrameMs:+p99.toFixed(2),
    maxFrameMs:+maxFrame.toFixed(2),
    averageFps:+(1000/mean).toFixed(1), onePercentLowFps:p99?+(1000/p99).toFixed(1):null,
    frameSpikes50ms:frameTimes.filter(ms=>ms>50).length, visibleTilePops:tilePops,
    streamingBusyFrames:busyFrames, peakTextures, peakCalls, peakTris, frameSpikeDetails:frameSpikes
  };
}
async function runAuto(){
  let views;
  if(/\.json$/.test(AUTO)){
    views=await (await fetch(AUTO)).json();
  }else{
    const q=new URLSearchParams(location.search);
    views=[{ name:q.get('name')||'view',
             pos:(q.get('pos')||'60,200,190').split(',').map(Number),
             yaw:+(q.get('yaw')||2.05), pitch:+(q.get('pitch')||0),
             time:q.get('time')!==null?+q.get('time'):undefined,
             ground:q.get('ground')==='1' }];
  }
  overlay.classList.add('hidden');
  labelGroup.visible=false;
  state.fly=true;                            // no gravity between waypoints
  let deferredRoutes=[];
  for(const v of views){
    if(v.waypoints){
      const routeMetrics=await runBenchmarkRoute(v);
      const settle=await settleStreams();
      const routeRecord=Object.assign(
        {name:v.name},routeMetrics,settle,{benchmarkRole:v.role||null});
      if(v.deferCapture){
        deferredRoutes.push(Object.assign({},routeRecord,{
          frameSpikeDetails:routeRecord.frameSpikeDetails.slice()
            .sort((a,b)=>b.dt-a.dt).slice(0,4)
        }));
        continue;
      }
      if(deferredRoutes.length){
        routeRecord.frameSpikeDetails=routeRecord.frameSpikeDetails.slice()
          .sort((a,b)=>b.dt-a.dt).slice(0,4);
        const batch=deferredRoutes.concat([Object.assign({},routeRecord)]);
        const response=await fetch('/route-batch',{
          method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(batch)
        });
        if(!response.ok) throw new Error('route batch upload failed: HTTP '+response.status);
      }
      if(!await saveShot(v.name,routeRecord))
        throw new Error('route capture failed');
      deferredRoutes=[];
      continue;
    }
    if(v.time!==undefined){ day.t=v.time; updateSun(true); }
    if(v.weather!==undefined){ window.WEATHER=v.weather; updateSun(true); }
    if(v.phase!==undefined){ window.MOON_PHASE=v.phase; updateSun(true); }
    if(v.time!==undefined || v.weather!==undefined || v.phase!==undefined)
      requestSkyEnvironmentRebake();
    if(v.season!==undefined) window.SEASON=v.season;   // 0 summer (default) · ~0.45 gold · 1 winter
    camera.fov=v.fov||66;
    camera.updateProjectionMatrix();
    realLabels.on = v.labels!==false;        // place names on unless the view opts out
    if(v.labelmode!==undefined) realLabels.mode=v.labelmode;   // 0 compass · 1 legacy pills · 2 off
    window.SHADOW_FORCE_OFF = v.shadow===false;   // real-cast-shadow kill switch (A/B perf pairs)
    if(v.drive){                             // spawn the car at pos, chase-cam per yaw/pitch
      drive.on=true; drive.used=true;
      drive.camMode=v.cam!==undefined?v.cam:0;   // 0 far chase · 1 near chase · 2 first person
      drive.camDist=drive.camMode===1?7.5:14;    // match the C-key cycle distances
      placeCar(v.pos[0], v.pos[2], v.yaw||0);
      state.yaw=v.yaw||0;
      state.pitch=v.pitch!==undefined?v.pitch:-0.18;
      drive.snapCam=true; state.vel.set(0,0,0); updateMode();
    }else{
      if(drive.on){ drive.on=false; updateMode(); }
      camera.position.set(v.pos[0], v.pos[1], v.pos[2]);
      if(v.ground) camera.position.y=sampleGround(v.pos[0],v.pos[2])+3;
      state.yaw=v.yaw||0; state.pitch=v.pitch||0; state.vel.set(0,0,0);
    }
    let settle={settleMs:0,settleTimedOut:false,coverageRequired:!v.nosettle};
    if(v.nosettle){
      await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));  // catch mid-pan transients
      settle.visibleTerrainCoverage=terrain&&terrain.coverageSnapshot?
        terrain.coverageSnapshot():null;
    }
    else settle=await settleStreams();
    const frameMetrics=await sampleFrames(v.benchmarkFrames||90);
    if(v.minimap && Minimap.isActive()){     // also capture the DOM minimap canvas itself
      await Minimap.ensureBase();
      Minimap.setMode(v.minimap==='follow'?2:1);
      Minimap.draw();
      if(!await saveMinimapShot(v.name+'-minimap')) throw new Error('minimap capture failed');
    }
    if(!await saveShot(v.name,Object.assign({},settle,frameMetrics,{benchmarkRole:v.role||null})))
      throw new Error('capture failed');
    if(v.hudshot){                           // composite DOM HUD proof shot (auto-<name>-hud.png)
      if(realLabels.ready){ splashClear(); if(v.splash) splashNearest(); }  // deterministic splash state
      if(!await saveHudShot(v.name)) throw new Error('HUD capture failed');
    }
  }
  document.title='AUTO_DONE';
}
